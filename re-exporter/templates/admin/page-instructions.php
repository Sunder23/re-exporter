	<h2 id="instr-faq">10. Частые вопросы</h2>

	<h3>Объявление не попадает в экспорт</h3>
	<p>Проверьте по порядку:</p>
	<ol>
		<li>Запись опубликована (или снят фильтр «Только опубликованные» в Разделе A).</li>
		<li>Флаг «Включить в экспорт» установлен на странице объявления (или снят фильтр «Учитывать флаг» в Разделе A).</li>
		<li>Объявлению назначена подкатегория через таксономию (B3/C3) или вручную в метабоксе.</li>
	</ol>

	<h3>Заголовок обрезается в OLX</h3>
	<p>OLX принимает заголовки не длиннее 70 символов. Плагин обрезает значение автоматически. Рекомендуется сразу делать заголовки в WordPress не длиннее 70 символов.</p>

	<h3>Как работает B5 / C5 при настройке категорий?</h3>
	<p>Если в B3 у термина заполнена только колонка «Продажа» — все объявления этого термина пойдут в эту подкатегорию. Если заполнены обе колонки («Продажа» и «Аренда») — плагин обращается к B5, чтобы определить тип сделки по значению поля WordPress.</p>

	<h3>Сколько изображений попадёт в файл?</h3>
	<p>Для OLX изображения объединяются через <code>|</code> без ограничения со стороны плагина (ограничение задаёт платформа). Для ALO максимум 15 URL.</p>

	<h3>Файл не скачивается / ошибка при экспорте</h3>
	<p>Убедитесь, что:</p>
	<ol>
		<li>Папка <code>wp-content/uploads/re-exporter/</code> существует и доступна для записи (права 755 или 775).</li>
		<li>Выбран тип записей в Разделе A и сохранены настройки.</li>
		<li>Хотя бы одному объявлению назначена категория (OLX или ALO).</li>
		<li>Если папок нет — деактивируйте и активируйте плагин заново (при активации папки создаются автоматически).</li>
	</ol>

	<h3>Что такое «field_map» в B4 (иконка <span class="re-badge-instr">values</span>)?</h3>
	<p>Некоторые категории OLX используют другой JSON-файл допустимых значений для одного и того же столбца. Например, в категории «Дома на продажу» столбец <code>floors</code> использует файл <code>house_floors.json</code> вместо стандартного <code>floors.json</code>. Плагин учитывает это автоматически — настраивать ничего не нужно.</p>

