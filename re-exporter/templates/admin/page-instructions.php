	<h2 id="instr-overview">1. Общий обзор</h2>

	<p>Плагин <strong>Real Estate Exporter</strong> позволяет экспортировать объявления о недвижимости из WordPress на две платформы:</p>
	<ul>
		<li><strong>OLX.bg</strong> &mdash; формат CSV (разделитель «;», кодировка UTF-8 с BOM). Для каждой подкатегории создаётся отдельный файл.</li>
		<li><strong>ALO.bg</strong> &mdash; формат JSON (UTF-8, pretty-print). Все объявления в одном файле на подкатегорию.</li>
	</ul>

	<p>Плагин работает на основе <strong>заранее настроенного маппинга</strong>: вы один раз указываете, какие поля WordPress соответствуют каким полям в CSV/JSON, а затем нажимаете «Экспорт» при каждом обновлении базы. Список объявлений формируется автоматически по фильтрам из Раздела A — вручную выбирать записи не нужно.</p>

