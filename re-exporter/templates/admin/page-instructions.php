	<h2 id="instr-metabox">6. Метабокс на странице объявления</h2>

	<p>На странице редактирования каждого объявления в боковой панели появляются один или несколько метабоксов:</p>

	<h3>RE Exporter — Export Settings</h3>
	<p>Галочка <strong>«Включить в экспорт»</strong>. По умолчанию включена для всех объявлений. Снимите, чтобы исключить конкретное объявление из всех будущих экспортов (работает только при включённом фильтре «Учитывать флаг» в Разделе A).</p>

	<h3>RE Exporter — OLX Category</h3>
	<p>Отображается <strong>только если</strong> в B3 не выбрана таксономия. Позволяет вручную назначить подкатегорию OLX для данного объявления.</p>

	<h3>RE Exporter — OLX Field Values</h3>
	<p>Появляется, если для назначенной категории OLX в B1 или B4 есть поля с источником «— Без источника (заполнять в метабоксе)». Позволяет указать значения для таких полей прямо на странице объявления: выбор из списка, ввод текста или числа, поиск города.</p>

