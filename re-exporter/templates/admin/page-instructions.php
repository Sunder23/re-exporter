	<h2 id="instr-field-rules">9. Правила обработки полей</h2>

	<p>При экспорте плагин автоматически применяет следующие правила к значениям полей:</p>

	<h3>OLX — поле <code>title</code></h3>
	<ul>
		<li>HTML-теги удаляются.</li>
		<li>Значение обрезается до <strong>70 символов</strong> (ограничение платформы OLX).</li>
	</ul>

	<h3>OLX — поле <code>description</code></h3>
	<ul>
		<li>HTML-теги удаляются.</li>
		<li>Эмодзи и все Unicode-символы за пределами букв, цифр, знаков препинания и пробелов удаляются.</li>
		<li>Лишние пробелы и переносы строк схлопываются в один пробел.</li>
	</ul>

	<h3>OLX — поле <code>images</code></h3>
	<ul>
		<li>Массив URL объединяется в строку через символ <code>|</code> (требование формата OLX).</li>
	</ul>

	<h3>OLX — поле <code>location_city</code></h3>
	<ul>
		<li>Если значение является числом — передаётся как есть (уже OLX ID).</li>
		<li>Если значение является строкой — автоматически запрашивается OLX API для получения числового ID города. Результат кешируется.</li>
	</ul>

	<h3>ALO — поля <code>desc</code>, <code>desc_en</code>, <code>desc_ru</code></h3>
	<ul>
		<li>HTML-теги удаляются.</li>
	</ul>

	<h3>ALO — поле <code>contacts.phones</code></h3>
	<ul>
		<li>Максимум 5 номеров телефона.</li>
	</ul>

	<h3>ALO — изображения</h3>
	<ul>
		<li>Максимум 15 URL.</li>
	</ul>

