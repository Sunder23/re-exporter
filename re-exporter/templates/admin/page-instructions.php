	<h2 id="instr-settings-global">3. Настройки — Раздел A (Общие)</h2>

	<h3>Тип записей (Post Type)</h3>
	<p>Выберите CPT, в котором хранятся объявления. Как правило, это <code>property</code>. После выбора и сохранения плагин подтягивает все поля ACF, мета-ключи и таксономии именно этого типа во всех таблицах маппинга.</p>

	<h3>Страна (Country)</h3>
	<p>Используется для автодополнения городов при заполнении поля <code>location_city</code> в метабоксе объявления. Выберите <em>Болгария</em> для работы с OLX.bg.</p>

	<h3>Фильтры экспорта</h3>
	<ul>
		<li><strong>Экспортировать только опубликованные</strong> &mdash; если снять галочку, в список попадут также черновики и скрытые записи.</li>
		<li><strong>Учитывать флаг «Включить в экспорт»</strong> &mdash; если включено, объявления с отключённым флагом (см. раздел 7) не попадут в экспорт. Рекомендуется оставить включённым.</li>
	</ul>

	<!-- ================================================================
	     4. OLX.bg — разделы B1–B5
	     ================================================================ -->
	<h2 id="instr-settings-olx">4. Настройки — OLX.bg (B1–B5)</h2>

	<h3>B1 — Маппинг полей</h3>
	<p>Таблица содержит <strong>все уникальные столбцы</strong> из CSV-шаблонов OLX. Для каждого столбца выберите источник данных из WordPress:</p>
	<ul>
		<li><code>Post Title</code> &mdash; заголовок записи (автоматически обрезается до 70 символов)</li>
		<li><code>Post Content</code> &mdash; содержимое (HTML-теги, эмодзи и символы удаляются автоматически)</li>
		<li><code>Post ID</code> &mdash; ID записи в WordPress</li>
		<li><code>Post URL</code> &mdash; ссылка на запись</li>
		<li><code>Featured Image</code> &mdash; миниатюра записи</li>
		<li>Поля ACF и мета-ключи &mdash; обнаруживаются автоматически по выборке из последних записей</li>
		<li><code>taxonomy:название</code> &mdash; термины таксономии (возвращается slug через запятую)</li>
		<li><strong>— Без источника (заполнять в метабоксе)</strong> &mdash; значение задаётся вручную на каждом объявлении; поддерживает выбор из допустимых значений OLX, ввод текста или числа</li>
	</ul>
	<p>Столбец <strong>— Пропустить —</strong> означает, что колонка будет пустой в CSV.</p>

	<div class="re-instr-tip">
		&#10003; Столбцы с меткой <span class="re-badge-instr">values</span> имеют файл допустимых значений от OLX. После сохранения маппинга для них появится таблица переводов в разделе B2.
	</div>

	<h3>B2 — Переопределение значений</h3>
	<p>Появляется только для столбцов, которые замаплены на источник и имеют JSON-файл допустимых значений OLX. В каждой строке слева — значение из WordPress, справа — выпадающий список допустимых значений OLX. Оставьте «— Оставить оригинал —», если значения уже совпадают.</p>

	<h3>B3 — Маппинг категорий</h3>
	<p>Определяет, в какой CSV-файл (подкатегорию OLX) попадёт объявление. Таблица содержит два столбца на каждый термин:</p>
	<ul>
		<li><strong>OLX категория (Продажа / Основная)</strong> &mdash; подкатегория для объявлений о продаже.</li>
		<li><strong>OLX категория (Аренда — опционально)</strong> &mdash; подкатегория для объявлений об аренде. Если не задана, все объявления термина идут в «Продажу».</li>
	</ul>
	<p>Если оба столбца заполнены, плагин определяет тип сделки через настройки B5. Если таксономия не выбрана — категория назначается в метабоксе каждого объявления.</p>

	<h3>B4 — Обязательные поля по категориям</h3>
	<p>Некоторые категории OLX требуют дополнительных столбцов (тип здания, этаж, отопление и т.д.). Если поле уже замаплено в B1 — показывается &#10003;. Если нет — здесь можно назначить источник только для этой категории, не добавляя столбец в общую таблицу B1.</p>

	<div class="re-instr-tip">
		Блоки B4 сворачиваемые. Нажмите на название категории, чтобы раскрыть. &#9888; предупреждение появляется для полей, которые ещё не замаплены.
	</div>

	<h3>B5 — Маршрутизация типа сделки (Продажа / Аренда)</h3>
	<p>Актуален, когда в B3 у одного термина заполнены оба столбца (Продажа и Аренда). Определяет, по какому полю WordPress различать тип сделки:</p>
	<ul>
		<li><strong>— Всегда Продажа —</strong> / <strong>— Всегда Аренда —</strong> &mdash; все объявления термина идут в один тип.</li>
		<li><strong>Поле WordPress</strong> &mdash; выберите поле с типом сделки и сопоставьте его значения («Продажа» → <em>Sales</em>, «Аренда» → <em>Rent</em>).</li>
	</ul>

	<!-- ================================================================
	     5. ALO.bg
	     ================================================================ -->
	<h2 id="instr-settings-alo">5. Настройки — ALO.bg (C1–C5)</h2>

	<h3>C1 — Маппинг полей</h3>
	<p>Таблица содержит фиксированный список полей формата ALO.bg. Принцип тот же, что в B1: выберите источник WordPress для каждого поля. Поля с меткой <span class="re-badge-instr" style="background:#fef9e7;color:#b45309;">required</span> обязательны для принятия файла платформой.</p>
	<p>Поля с точкой в названии (например, <code>map.lat</code>, <code>contacts.phones</code>) автоматически формируют вложенные объекты в итоговом JSON.</p>

	<h3>C2 — Переопределение значений</h3>
	<p>Работает аналогично B2. Позволяет перевести значения из WordPress в допустимые значения ALO.bg для полей с контролируемым словарём.</p>

	<h3>C3 — Маппинг категорий</h3>
	<p>Таблица аналогична B3: два столбца (Продажа / Аренда) для каждого термина. Сопоставьте термины таксономии с числовыми <code>subcat_id</code> платформы ALO.bg.</p>

	<h3>C4 — Обязательные поля по категориям</h3>
	<p>Аналогично B4. Для полей, не вошедших в C1 (категорийно-специфичные), здесь назначается источник.</p>

	<h3>C5 — Маршрутизация типа сделки</h3>
	<p>Аналогично B5. Используется, когда в C3 у термина заполнены оба столбца.</p>

