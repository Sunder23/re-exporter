	<h2 id="instr-list-table">7. Список записей — Quick Edit и Bulk Edit</h2>

	<p>В списке объявлений (<em>WordPress → тип записи → список</em>) добавлена колонка <strong>Export</strong>, которая показывает текущее состояние флага: &#10003; (включён) или — (выключен).</p>

	<h3>Quick Edit (Быстрое редактирование)</h3>
	<p>Нажмите «Быстрое редактирование» под нужной записью. В открывшейся строке появится галочка <strong>«Include in RE export»</strong>. Она автоматически предзаполняется текущим значением флага. Снимите или установите галочку и нажмите «Обновить».</p>

	<h3>Bulk Edit (Массовое редактирование)</h3>
	<p>Отметьте несколько записей, выберите в выпадающем меню «Изменить» и нажмите «Применить». В строке массового редактирования появится выпадающий список <strong>«RE Export»</strong> с тремя вариантами:</p>
	<ul>
		<li><strong>— Без изменений —</strong> &mdash; флаг текущих записей не меняется.</li>
		<li><strong>Включить</strong> &mdash; установить флаг для всех выбранных записей.</li>
		<li><strong>Исключить</strong> &mdash; снять флаг для всех выбранных записей.</li>
	</ul>

